// Pick the best translation from a {lang: text} object.
export function pick(obj, lang, fallback = 'el') {
  if (!obj) return '';
  if (typeof obj === 'string') return obj;
  return obj[lang] || obj.en || obj[fallback] || Object.values(obj)[0] || '';
}

